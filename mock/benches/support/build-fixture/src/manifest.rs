//! The manifests and the lockfile of the fixture workspace.
//!
//! The fixture has no dependency outside itself, so its lockfile is the list
//! of its own packages and their edges, and cargo builds it offline and locked.
//! The profiles are the fixture's own: `dev` at opt-level 1 with no debug
//! information, the shape of kaski's workspace `dev`, and `release` at
//! opt-level 3 with one codegen unit. Nothing else of the build is set here.

use crate::graph::{Graph, Role, dir, name};

/// The workspace manifest.
///
/// The two profiles hold `opt-level`, debug information and codegen units,
/// which hilavitkutin-build's design leaves to a consumer's manifest, and
/// the fixture is the consumer here. What the crate does own of a profile,
/// the keys of an arm's pragmas, is not in this file: the call hands those
/// to cargo on its command line (`build-call`'s `cargo::command`).
pub fn workspace() -> String {
    "[workspace]\nmembers = [\"crates/*\", \"facade\"]\nresolver = \"3\"\n\n\
     [workspace.package]\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n\
     [profile.dev]\nopt-level = 1\ndebug = 0\n\n\
     [profile.release]\nopt-level = 3\ncodegen-units = 1\n"
        .to_string()
}

/// The manifest of one crate.
pub fn package(graph: &Graph, role: Role) -> String {
    let mut t = format!(
        "[package]\nname = \"{}\"\nversion.workspace = true\nedition.workspace = true\npublish.workspace = true\n",
        name(role)
    );
    if role == Role::Facade {
        t.push_str("\n[[bin]]\nname = \"fx_facade\"\npath = \"src/main.rs\"\n");
    }
    let deps = graph.deps(role);
    if !deps.is_empty() {
        t.push_str("\n[dependencies]\n");
        let here = dir(role);
        let up = if here.contains('/') { "../.." } else { ".." };
        for d in deps {
            t.push_str(&format!("{} = {{ path = \"{up}/{}\" }}\n", name(d), dir(d)));
        }
    }
    t
}

/// The lockfile cargo would write for this workspace, in its version 4 form.
pub fn lockfile(graph: &Graph) -> String {
    let mut entries: Vec<(String, Vec<String>)> = graph
        .roles()
        .into_iter()
        .map(|r| {
            let mut deps: Vec<String> = graph.deps(r).into_iter().map(name).collect();
            deps.sort();
            (name(r), deps)
        })
        .collect();
    entries.sort();
    let mut t = String::from(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n",
    );
    for (n, deps) in entries {
        t.push_str(&format!(
            "\n[[package]]\nname = \"{n}\"\nversion = \"0.0.0\"\n"
        ));
        if !deps.is_empty() {
            t.push_str("dependencies = [\n");
            for d in deps {
                t.push_str(&format!(" \"{d}\",\n"));
            }
            t.push_str("]\n");
        }
    }
    t
}
